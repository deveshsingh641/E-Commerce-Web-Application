import mongoose from 'mongoose';

/**
 * Escapes regex special characters to prevent ReDoS and Regex Injection vulnerabilities.
 */
export const escapeRegex = (string) => {
  if (typeof string !== 'string') return '';
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
};

/**
 * Checks whether an ID string is a valid MongoDB ObjectId.
 */
export const isValidObjectId = (id) => {
  return mongoose.Types.ObjectId.isValid(id) && String(new mongoose.Types.ObjectId(id)) === String(id);
};

/**
 * Express middleware to validate an ObjectId parameter in request params.
 */
export const validateObjectIdParam = (paramName = 'id') => {
  return (req, res, next) => {
    const id = req.params[paramName];
    if (!id || !isValidObjectId(id)) {
      return res.status(400).json({
        success: false,
        message: `Invalid identifier format for parameter '${paramName}': ${id}`,
      });
    }
    next();
  };
};

/**
 * Validates email format.
 */
export const isValidEmail = (email) => {
  if (typeof email !== 'string') return false;
  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  return emailRegex.test(email.trim());
};
